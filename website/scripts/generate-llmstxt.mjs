#!/usr/bin/env node
/** Post-build: generate llms.txt + llms-full.txt from the Next.js static export. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(__dirname, '..', 'out');
const PUBLIC_DIR = path.resolve(__dirname, '..', 'public');
const SITE_URL = 'https://aicrowd.github.io';
const BASE_PATH = '/whestbench';

const SECTIONS = {
  'Participant Guide': {
    'participant-guide': 'Tutorial, concepts, how-to, and troubleshooting (from whest-starterkit)',
  },
  'Guides': {
    'guides/datasets': 'Working with whestbench datasets',
  },
  'How-to': {
    'how-to/parallel-bake': 'Bake datasets in parallel',
    'how-to/publish-to-hf-hub': 'Publish a dataset to the Hugging Face Hub',
  },
  'Reference': {
    'reference/estimator-contract': 'The estimator contract participants implement',
    'reference/score-report-fields': 'Fields in the score report',
    'reference/rounds': 'Per-round MLP shape, FLOP budget, and wall-time rules',
    'reference/dataset-format': 'On-disk dataset format',
    'reference/cli-reference': 'CLI overview',
    'reference/code-patterns': 'flopscope cheat sheet',
    'reference/flopscope-primer': 'BudgetContext and FLOP costs',
    'reference/gpu-dataset-generation': 'Bake large datasets on GPU with the torch backend',
  },
  'CLI': {
    'cli': 'Autogenerated per-command reference for the whest CLI',
  },
  'API Reference': {
    'api': 'Autogenerated reference for the whestbench public API',
  },
  'Development': {
    'development/release-process': 'Release process',
  },
  'Changelog': {
    'changelog': 'Release history',
  },
};

function extractText(htmlPath) {
  const dom = new JSDOM(fs.readFileSync(htmlPath, 'utf-8'));
  const doc = dom.window.document;
  for (const sel of ['script','style','nav','header','footer','[data-sidebar]','[data-toc]','.fd-toc','.fd-sidebar','.fd-nav','[role="navigation"]']) {
    for (const el of doc.querySelectorAll(sel)) el.remove();
  }
  const article = doc.querySelector('article') || doc.querySelector('main') || doc.body;
  return (article.textContent || '').replace(/\n{3,}/g, '\n\n').trim();
}

function resolveHtmlPath(slug) {
  for (const candidate of [
    path.join(OUT_DIR, 'docs', slug, 'index.html'),
    path.join(OUT_DIR, slug, 'index.html'),
    path.join(OUT_DIR, slug + '.html'),
  ]) {
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

const siteBase = `${SITE_URL}${BASE_PATH}/`;
const idx = ['# whestbench', '', '> White-box estimation of MLP output statistics under a FLOP budget', ''];
const full = [];
let missing = 0;

for (const [section, pages] of Object.entries(SECTIONS)) {
  idx.push(`## ${section}`, '');
  full.push('='.repeat(60), section, '='.repeat(60), '');
  for (const [slug, description] of Object.entries(pages)) {
    const htmlPath = resolveHtmlPath(slug);
    const isDocs = htmlPath && htmlPath.includes(path.join('out', 'docs'));
    const url = `${siteBase}${isDocs ? `docs/${slug}` : slug}`;
    idx.push(`- [${description}](${url})`);
    full.push(`--- ${slug} ---`, `URL: ${url}`, '');
    if (htmlPath) full.push(extractText(htmlPath), '');
    else { full.push('[Page not found in build output]', ''); missing++; }
  }
  idx.push('');
}

if (missing > 0) throw new Error(`[generate-llmstxt] ${missing} declared page(s) missing from build output`);

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.mkdirSync(PUBLIC_DIR, { recursive: true });
for (const [p, data] of [
  [path.join(OUT_DIR, 'llms.txt'), idx.join('\n')],
  [path.join(OUT_DIR, 'llms-full.txt'), full.join('\n')],
  [path.join(PUBLIC_DIR, 'llms.txt'), idx.join('\n')],
  [path.join(PUBLIC_DIR, 'llms-full.txt'), full.join('\n')],
  [path.join(OUT_DIR, '.nojekyll'), ''],
]) fs.writeFileSync(p, data, 'utf-8');

console.log(`[generate-llmstxt] wrote llms.txt + llms-full.txt (${missing} missing)`);
